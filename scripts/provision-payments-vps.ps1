$sshOpts = @(
  "-o", "UserKnownHostsFile=$KnownHosts",
  "-o", "StrictHostKeyChecking=accept-new",
  "-o", "ConnectTimeout=10",
  "-o", "ServerAliveInterval=15",
  "-i", $KeyPath
