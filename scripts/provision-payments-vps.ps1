$remoteProbe = @'
set -e
service=0
env=0
nginx=0
node=0
current_backend=0
if command -v node >/dev/null 2>&1; then node=1; fi
if systemctl list-unit-files qflash-payments.service --no-legend 2>/dev/null | grep -q qflash-payments; then service=1; fi
if sudo test -s /etc/qflash-payments.env; then env=1; fi
