Type=simple
WorkingDirectory=$remote_root/current
Environment=NODE_ENV=production
EnvironmentFile=/etc/qflash-payments.env
ExecStart=/usr/bin/node server/dist/index.js
Restart=on-failure
RestartSec=3
User=www-data
Group=www-data

[Install]
WantedBy=multi-user.target
UNIT

nginx_file="$(sudo grep -RslE 'server_name[[:space:]].*unlock\.choimaytau\.com' /etc/nginx/sites-enabled /etc/nginx/sites-available /etc/nginx/conf.d 2>/dev/null | head -n 1 || true)"
