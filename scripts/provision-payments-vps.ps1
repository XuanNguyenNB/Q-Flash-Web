function Read-EnvFile {
  param([Parameter(Mandatory)][string]$Path)

  $map = [ordered]@{}
  foreach ($line in Get-Content -LiteralPath $Path) {
    if ($line -match '^\s*$' -or $line -match '^\s*#') {
      continue
    }
    if ($line -notmatch '^([^=]+)=(.*)$') {
      throw "Invalid env line in $Path. Expected KEY=value format."
    }
    $name = $Matches[1].Trim()
    $value = $Matches[2]
    if ($name -match '\s') {
      throw "Invalid env key '$name' in $Path."
    }
    $map[$name] = $value
  }
  return $map
}

function Require-SecretValue {
  param(
    [Parameter(Mandatory)][hashtable]$Map,
    [Parameter(Mandatory)][string]$Name
  )

  if (-not $Map.Contains($Name) -or [string]::IsNullOrWhiteSpace([string]$Map[$Name])) {
    throw "$Name is required in $EnvPath."
  }
}

function Write-EnvFile {
  param(
    [Parameter(Mandatory)][hashtable]$Map,
    [Parameter(Mandatory)][string]$Path
  )

  $lines = New-Object System.Collections.Generic.List[string]
  $lines.Add("# Generated by scripts/provision-payments-vps.ps1. Do not commit.")
  foreach ($key in $Map.Keys) {
    $lines.Add("$key=$($Map[$key])")
  }
  [System.IO.File]::WriteAllText(
    $Path,
    (($lines -join [Environment]::NewLine) + [Environment]::NewLine),
    (New-Object System.Text.UTF8Encoding($false))
  )
}

function Invoke-Ssh {
  param([Parameter(Mandatory)][string]$Command)
  $oldErrorActionPreference = $ErrorActionPreference
  $ErrorActionPreference = "Continue"
  try {
    $output = & ssh @sshOpts -o BatchMode=yes $HostTarget $Command 2>&1
    $exitCode = $LASTEXITCODE
  } finally {
    $ErrorActionPreference = $oldErrorActionPreference
  }
  if ($exitCode -ne 0) {
    $text = ($output | Out-String).Trim()
    throw "SSH command failed with exit code $exitCode. $text"
  }
  return $output
}

function Invoke-Scp {
  param([Parameter(Mandatory)][string[]]$Arguments)

  $oldErrorActionPreference = $ErrorActionPreference
  $ErrorActionPreference = "Continue"
  try {
    & scp @sshOpts -q @Arguments
    $exitCode = $LASTEXITCODE
  } finally {
    $ErrorActionPreference = $oldErrorActionPreference
  }
  if ($exitCode -ne 0) {
    throw "SCP failed with exit code $exitCode."
  }
}

