sudo rm -f /tmp/qflash-payments.env /tmp/qflash-payment-asset-keys.local.json

sudo tee /etc/systemd/system/qflash-payments.service >/dev/null <<UNIT
[Unit]
Description=Q Flash Web payments API
After=network.target

